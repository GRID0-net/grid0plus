-- A console, as identified by its TLS client certificate.
--
-- This table is informational: it drives the dashboard's device list and lets
-- an operator see which consoles have talked to the server. Nothing about
-- authorisation depends on it.
--
-- If nginx is not configured to pass the console's client certificate through,
-- every console derives the same device id and this table holds one row. That
-- is harmless, because account identity is resolved from the device account in
-- 0002's other table, never from the device id.
CREATE TABLE devices (
    id             CHAR(16) PRIMARY KEY,
    serial_number  TEXT        NOT NULL DEFAULT '',
    product_code   TEXT        NOT NULL DEFAULT 'HAC',
    device_type    TEXT        NOT NULL DEFAULT 'NX Prod 1',
    ist            BOOLEAN     NOT NULL DEFAULT FALSE,
    system_version TEXT        NOT NULL DEFAULT '',
    first_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A BAAS device account: the credential the console stores and presents on
-- every login. This is the ONLY thing that resolves a request to an account.
--
-- The console caches its device account in system save 8000000000000010 and
-- presents it forever. That is why identity has to be resolved from it strictly:
-- if a lookup misses, the answer is an authentication error, never a fallback to
-- "the last account that logged in". A fallback like that makes every console
-- act as one person, which is how a friends system ends up showing everybody the
-- same friend code.
CREATE TABLE device_accounts (
    id            CHAR(16) PRIMARY KEY,
    user_id       CHAR(16)    NOT NULL REFERENCES users (id) ON DELETE CASCADE,

    -- SHA-256 of the password, hex-encoded.
    --
    -- The password is 40 characters drawn from a 62-character alphabet, so it
    -- carries about 238 bits of entropy and is generated by the server, never
    -- chosen by a person. A slow key derivation function protects against
    -- guessing a low-entropy secret; there is nothing to guess here, so a plain
    -- SHA-256 is the right tool and keeps login cheap enough that a console
    -- polling on a slow connection is not held up by it.
    password_sha256 CHAR(64)  NOT NULL,

    -- The device this account was created on, when known.
    device_id     CHAR(16)    REFERENCES devices (id) ON DELETE SET NULL,

    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set instead of deleting the row, so a console that keeps presenting a
    -- deleted device account gets a clear rejection rather than a lookup miss
    -- that could be confused with a bug.
    deleted_at    TIMESTAMPTZ
);

CREATE INDEX device_accounts_user_idx ON device_accounts (user_id);
