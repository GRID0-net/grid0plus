// DNS generators.
//
// SwitchNet does not run its own DNS server. These generate configuration for
// a resolver the operator already runs -- their router, Pi-hole or Unbound --
// so adding these lines there redirects every console at once with no
// per-console configuration and nothing at all on the SD card.
//
// Both generators read the same host list as everything else, so a hostname
// cannot be redirected by one mechanism and missed by another.
//
// # The AAAA trap
//
// Both configurations are written so that an AAAA query for a redirected name
// gets NODATA rather than being forwarded. If AAAA were forwarded while A was
// answered locally, a console with IPv6 on its network would resolve Nintendo's
// real address and talk straight past SwitchNet — intermittently, which is the
// worst kind of bug to chase from the console side.
//
// dnsmasq's `address=` already behaves this way. Unbound needs `local-zone`
// type `static`; `transparent` and `redirect` both leak AAAA upstream.

func requirePublicIP(cfg config.Config) {
	if cfg.Network.PublicIP == "" {
		fmt.Fprintln(os.Stderr,
			"switchnetctl: network.public_ip is not set, so there is no address to "+
				"point the consoles at. Set it in config.yaml or as SWITCHNET_PUBLIC_IP.")
		os.Exit(1)
	}
}

// natCheckAddr returns the address a NAT-check host should resolve to, and
// whether the two-address requirement is satisfied.
func natCheckAddr(cfg config.Config, pattern string) (addr string, warn bool) {
	if !strings.HasPrefix(pattern, "nncs2") {
		return cfg.Network.PublicIP, false
	}
	if cfg.Network.NATCheckSecondaryIP == "" {
		return cfg.Network.PublicIP, true
	}
	return cfg.Network.NATCheckSecondaryIP, false
}

// dnsSuffixOf turns an Atmosphère wildcard pattern into the fixed DNS suffix
// underneath it, which is what a resolver can match on. Atmosphère's '*' and '%'
// are not DNS syntax.
func dnsSuffixOf(pattern string) string {
	idx := strings.LastIndexAny(pattern, "*%")
	if idx < 0 {
		return pattern
	}
	return strings.TrimPrefix(pattern[idx+1:], ".")
}

// redirectedServices are the services whose hosts point at SwitchNet, in the
// order they should be emitted.
var redirectedServices = []nintendo.Service{
	nintendo.ServiceDAuth,
	nintendo.ServiceAAuth,
	nintendo.ServiceBAAS,
	nintendo.ServiceStubs,
	nintendo.ServiceNPLNRest,
	nintendo.ServiceNPLN,
	nintendo.ServiceNEX,
}

// ---- dnsmasq -------------------------------------------------------------

func dnsmasqConf(cfg config.Config) string {
	var b strings.Builder

	b.WriteString(`# ==========================================================
#  SwitchNet - dnsmasq / Pi-hole / OpenWrt
#  GENERATED by 'switchnetctl dnsmasq'. Regenerate rather than edit.
#
#  Install:
#    dnsmasq   /etc/dnsmasq.d/switchnet.conf
#    Pi-hole   /etc/dnsmasq.d/99-switchnet.conf
#    OpenWrt   append to /etc/dnsmasq.conf
#  then restart the resolver.
#
#  Nothing is installed on the console. Either the router hands this resolver
#  out over DHCP, in which case the console needs no configuration at all, or
#  the console's DNS is set manually in its own network settings.
#
#  'address=/name/ip' matches the name and everything under it, and answers
#  AAAA with NODATA. Both matter: answering A here while letting AAAA through
#  would hand a console Nintendo's real IPv6 address.
# ==========================================================
`)

	section := func(title string) {
		b.WriteString("\n# --- " + title + " ---\n")
	}

	section("accounts, friends and authentication")
	for _, svc := range redirectedServices[:3] {
		for _, h := range nintendo.ServiceHosts(svc) {
			fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, cfg.Network.PublicIP)
		}
	}

	section("stubs: answered, not implemented")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceStubs) {
		fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, cfg.Network.PublicIP)
	}

	section("NPLN game servers (phase 2)")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceNPLNRest) {
		fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, cfg.Network.PublicIP)
	}
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceNPLN) {
		fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, cfg.Network.PublicIP)
	}

	section("NEX game servers: Splatoon 2")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceNEX) {
		fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, cfg.Network.PublicIP)
	}

	section("NAT check")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceNATCheck) {
		addr, warn := natCheckAddr(cfg, h.Pattern)
		if warn {
			b.WriteString("# WARNING: network.natcheck_secondary_ip is unset, so nncs2 points at the\n")
			b.WriteString("# same address as nncs1. The console de-duplicates its second NAT probe\n")
			b.WriteString("# and NAT detection never completes.\n")
		}
		fmt.Fprintf(&b, "address=/%s/%s\n", h.Pattern, addr)
	}

	section("telemetry: null-routed")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceBlackhole) {
		fmt.Fprintf(&b, "address=/%s/0.0.0.0   # %s\n", dnsSuffixOf(h.Pattern), h.Comment)
	}

	section("deliberately NOT redirected")
	b.WriteString("# Commented out so nobody adds them by mistake. A redirected system\n")
	b.WriteString("# update host makes nim write a persistent flag that survives switching\n")
	b.WriteString("# back to Nintendo. The eShop hosts are phase 3.\n")
	for _, h := range nintendo.ServiceHosts(nintendo.ServicePassthrough) {
		fmt.Fprintf(&b, "# address=/%s/%s   # %s\n",
			h.Pattern, cfg.Network.PublicIP, h.Comment)
	}

	return b.String()
}

// ---- unbound -------------------------------------------------------------

func unboundConf(cfg config.Config) string {
	ttl := cfg.DNS.TTL
	if ttl <= 0 {
		ttl = 60
	}

	var b strings.Builder

	b.WriteString(`# ==========================================================
#  SwitchNet - unbound
#  GENERATED by 'switchnetctl unbound'. Regenerate rather than edit.
#
#  Include from unbound.conf inside the server: clause, or drop in
#  /etc/unbound/unbound.conf.d/switchnet.conf.
#
#  'static' is deliberate. It answers every type in the zone from local-data
#  only, so an AAAA query gets NODATA. 'transparent' and 'redirect' both
#  forward AAAA upstream, which would hand a console Nintendo's real IPv6
#  address.
# ==========================================================

`)

	emit := func(name, addr, comment string) {
		fmt.Fprintf(&b, "# %s\n", comment)
		fmt.Fprintf(&b, "local-zone: \"%s.\" static\n", name)
		fmt.Fprintf(&b, "local-data: \"%s. %d IN A %s\"\n\n", name, ttl, addr)
	}

	for _, svc := range redirectedServices {
		for _, h := range nintendo.ServiceHosts(svc) {
			emit(h.Pattern, cfg.Network.PublicIP, h.Comment)
		}
	}

	for _, h := range nintendo.ServiceHosts(nintendo.ServiceNATCheck) {
		addr, warn := natCheckAddr(cfg, h.Pattern)
		comment := h.Comment
		if warn {
			comment += " -- WARNING: same address as nncs1, NAT detection will not complete"
		}
		emit(h.Pattern, addr, comment)
	}

	b.WriteString("# --- telemetry: null-routed ---\n")
	for _, h := range nintendo.ServiceHosts(nintendo.ServiceBlackhole) {
		emit(dnsSuffixOf(h.Pattern), "0.0.0.0", h.Comment)
	}

	b.WriteString("# --- deliberately NOT redirected ---\n")
	b.WriteString("# Do not add these. A redirected system update host makes nim write a\n")
	b.WriteString("# persistent flag that survives switching back to Nintendo.\n")
	for _, h := range nintendo.ServiceHosts(nintendo.ServicePassthrough) {
		fmt.Fprintf(&b, "#   %-46s %s\n", h.Pattern, h.Comment)
	}

	return b.String()
}
